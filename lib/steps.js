export function findStep(stepId){
  return STEPS.find(s => s.id === Number(stepId));
}
export function findLevel(levelKey){
  return LEVELS.find(l => l.key === levelKey);
}
export function findGroup(groupKey){
  return GROUPS.find(g => g.key === groupKey);
}

export function buildPromptText(step, levelKey, condition){
  return step.prompts[condition === "clue" ? "clue" : "full"][levelKey];
}

// 系統指令：13條共同AI生成規定 + 目前任務情境 + 學生選擇的認知方向。
// 學生實際送出的訊息（promptText）另外以「使用者訊息」傳給模型，不寫在這裡。
export function buildSystemInstruction(step, levelKey, condition){
  const level = findLevel(levelKey);
  const conditionLabel = condition === "clue" ? "線索任務型" : "完整任務型";
  const lines = [
    "你是 Delightex 程式設計課堂中的 AI 提問小幫手，服務對象是國小三年級學生，正在使用 CoBlocks 積木完成一個闖關遊戲（阿煌的密室逃脫任務）。無論學生目前是完整任務型或線索任務型，你都必須遵守以下規則：",
    ""
  ];
  RULES.forEach((r, i) => lines.push(`${i + 1}. ${r}`));
  lines.push("");

  const fields = condition === "clue" ? CLUE_REPLY_FIELDS : FULL_REPLY_FIELDS;
  const fieldLines = fields.map(([name, desc]) => `「${name}」（${desc}）`).join("、");
  if (condition === "clue") {
    lines.push(`${conditionLabel}的回覆原則：你的回覆只能呈現「部分」線索，逐步引導、不一次講完。內容概念上可以涵蓋以下面向，但每次只挑跟學生這句話最相關的1〜2項來回覆，不必也不要每項都提到，更不要條列標籤或表格：${fieldLines}。`);
  } else {
    lines.push(`${conditionLabel}的回覆原則：你的回覆要像一份較完整、結構化的分析，但仍要遵守上面「句子簡短、一次只說一個重點」的規則。內容概念上可以涵蓋以下面向，依學生這句話實際問到的部分挑其中幾項自然地融入說明即可，不必也不要每項都提到，更不要條列標籤或表格：${fieldLines}。`);
  }
  lines.push("");
  lines.push(`目前任務情境：${step.scenario}（${step.title}）`);
  lines.push(`學生選擇的協助方式：「${level.studentLabel}」（正式名稱：${level.formalName}。${level.def}）`);
  lines.push("");
  lines.push("接下來會收到學生送出的訊息，請只針對那句話、只用這一種認知方向回覆。不要覆述學生的問題，不要加開場白或客套話，不要提到「規則」兩個字，不要用條列或表格格式，用自然的口語句子回覆。");
  return lines.join("\n");
}
